export type Lang = "en" | "el";
export const LANGS: Lang[] = ["en", "el"];
export const DEFAULT_LANG: Lang = "en";

export function isLang(v: string | undefined | null): v is Lang {
  return v === "en" || v === "el";
}

/** Path helpers: English lives at "/", Greek at "/el". */
export function localePath(lang: Lang, path = "/") {
  const clean = path.startsWith("/") ? path : `/${path}`;
  if (lang === "en") return clean;
  return clean === "/" ? "/el" : `/el${clean}`;
}

export function htmlLang(lang: Lang) {
  return lang === "el" ? "el" : "en";
}

export function localeTag(lang: Lang) {
  return lang === "el" ? "el-GR" : "en-GB";
}

